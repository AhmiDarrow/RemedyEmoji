/// Polylines for `text`, centred on `cx`, sitting on `baseline`, `height` tall.
pub fn layout(text: &str, cx: f32, baseline: f32, height: f32) -> Vec<Vec<[f32; 2]>> {
    let unit = height / HEIGHT;
    let count = text.chars().count() as f32;
    if count == 0.0 {
        return Vec::new();
    }
    let total = (count - 1.0) * ADVANCE + WIDTH;
    let left = cx - total * unit / 2.0;
    let top = baseline - height;
    let mut out = Vec::new();
    for (i, c) in text.chars().enumerate() {
        let ox = left + i as f32 * ADVANCE * unit;
        for stroke in strokes(c).split('|') {
            let mut line = Vec::new();
            for pair in stroke.split_whitespace() {
                let Some((x, y)) = pair.split_once(',') else { continue };
                let (Ok(x), Ok(y)) = (x.parse::<f32>(), y.parse::<f32>()) else { continue };
                line.push([ox + x * unit, top + y * unit]);
            }
            if line.len() >= 2 {
                out.push(line);
            }
        }
    }
    out
}
